/**
 * ارقام را از اعداد حرفی می‌سازد.
 *
 * قاعده: یک گروه عددی فارسی حداکثر یک صدگان، یک دهگان و یک یکان دارد،
 * و به ترتیب نزولی می‌آیند. پس هر بار که دسته‌ای تکرار شود، گروه تازه شروع شده.
 *
 * همین قاعده ابهام را حل می‌کند:
 *   «هفتاد و هشت»   → یک گروه  → 78
 *   «هفتاد و هشت نه» → دو گروه  → 78 و 9   (نه یکانِ دوم است)
 *   «هشت هشت»       → دو گروه  → 8 و 8
 *   «بیست و یک»     → یک گروه  → 21
 *
 * مثال کامل:
 *   «صفر نهصد و دوازده سیصد و چهل و پنج ششصد و هفتاد و هشت نه»
 *   → 0 | 912 | 345 | 678 | 9  →  09123456789
 */
function fa_digits_from_words(string $text): string
{
    $out  = '';
    $sum  = 0;
    $used = [];

    $flush = function () use (&$sum, &$used, &$out): void {
        if ($used) {
            $out .= (string) $sum;
        }
        $sum  = 0;
        $used = [];
    };

    foreach (explode(' ', fa_norm($text)) as $t) {
        if ($t === 'و') {
            continue;
        }
        if (!isset(FA_NUM[$t])) {
            $flush();
            continue;
        }
        $cat = FA_NUM_CAT[$t] ?? 4;
        if ($cat === 0) {                    // «صفر» = یک رقم مستقل
            $flush();
            $out .= '0';
            continue;
        }
        if (isset($used[$cat])) {            // دسته تکرار شد → گروه تازه
            $flush();
        }
        $sum += FA_NUM[$t];
        $used[$cat] = true;
    }
    $flush();

    return $out;
}

/* ───────────── استخراج شمارهٔ تماس ───────────── */

/** فقط ارقام متن (بعد از نرمال‌سازی همه لاتین شده‌اند) */
function fa_digits_literal(string $text): string
{
    return (string) preg_replace('/[^0-9]+/', '', fa_chars($text));
}

/** یک رشتهٔ ارقام را به معتبرترین شکل شمارهٔ ایران درمی‌آورد */
function fa_phone_shape(string $d): ?string
{
    $d = (string) preg_replace('/\D+/', '', $d);
    if ($d === '') {
        return null;
    }
    if (strpos($d, '0098') === 0) {
        $d = '0' . substr($d, 4);
    } elseif (strpos($d, '98') === 0 && strlen($d) >= 12) {
        $d = '0' . substr($d, 2);
    }
    if (preg_match('/^09\d{9}$/', $d)) {          // موبایل
        return $d;
    }
    if (preg_match('/^9\d{9}$/', $d)) {           // موبایل بدون صفر
        return '0' . $d;
    }
    // تلفن ثابت: ۰۲۱ + ۸ رقم = ۱۱ رقم. عدد کوتاه‌تر ناقص است و باید رد شود،
    // وگرنه رزرو با شمارهٔ غلط ثبت می‌شود.
    if (preg_match('/^0\d{10}$/', $d)) {
        return $d;
    }
    if (preg_match('/(09\d{9})/', $d, $m)) {      // موبایل داخل رشتهٔ بلندتر
        return $m[1];
    }
    return null;
}

/** شمارهٔ تماس را از متن می‌کشد بیرون — چه ارقام، چه حروف */
function fa_phone(string $text): ?string
{
    $cands = array_merge(
        [fa_digits_literal($text)],   // ارقام صریح: «۰۹۱۲۴۵۶۷۸۹۰»
        [fa_digits_from_words($text)] // اعداد حرفی: «صفر نهصد و دوازده…»
    );
    foreach ($cands as $c) {
        if (strlen($c) >= 10) {
            $p = fa_phone_shape($c);
            if ($p !== null) {
                return $p;
            }
        }
    }
    return null;
}

