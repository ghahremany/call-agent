const FA_CONFIRM = [
    'بله','آره','اره','اوکی','اوکیه','باشه','تایید','تاییده','درسته','خوبه',
    'همینه','همون خوبه','همون','ثبت کن','ثبتش کن','قبوله','مناسبه','تاییدش کن',
    'تایید کنید','بفرمایید ثبت کنید',
];

const FA_REJECT = [
    'نه','خیر','وقت دیگه','یه وقت دیگه','زمان دیگه','ساعت دیگه','زودتر','دیرتر',
    'بعدی','مورد دیگه','نمیشه','نمی شه','نمی خوام','نمیخوام','نمی تونم','نمیتونم',
];

const FA_FAREWELL = [
    'ممنونم','ممنون','مرسی','خیلی ممنون','خداحافظ','خدا نگهدار','خسته نباشید','روز بخیر',
];

function fa_is_confirm(string $text): bool
{
    return fa_has_phrase($text, FA_CONFIRM);
}

function fa_is_reject(string $text): bool
{
    return fa_has_phrase($text, FA_REJECT);
}

/** فقط وقتی کل جمله یک خداحافظی است (نه «ممنون» در میان حرف) */
function fa_is_farewell_only(string $text): bool
{
    $p = trim(fa_plain($text));
    foreach (FA_FAREWELL as $f) {
        if ($p === $f) {
            return true;
        }
    }
    return false;
}

