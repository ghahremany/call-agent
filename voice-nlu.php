/**
 * نام را از جمله بیرون می‌کشد: «اسمم مریم رضایی هست» → «مریم رضایی»
 * اگر چیزی که می‌ماند شبیه نام نباشد، null برمی‌گرداند تا AI تصمیم بگیرد.
 */
function fa_name(string $text): ?string
{
    if (strpos($text, '?') !== false || strpos($text, '؟') !== false) {
        return null;   // جملهٔ پرسشی هیچ‌وقت نام نیست
    }

    $n = fa_norm($text);
    if ($n === '') {
        return null;
    }

    $keep = [];
    foreach (explode(' ', $n) as $t) {
        if ($t === '' || is_numeric($t)) {
            continue;
        }
        if (isset(FA_NUM[$t]) || $t === 'و') {
            continue;
        }
        if (in_array($t, FA_NAME_STOP, true)) {
            continue;
        }
        if (fa_len($t) < 2) {
            continue;
        }
        $keep[] = $t;
    }

    if (!$keep || count($keep) > 4) {
        return null;
    }
    $name = implode(' ', $keep);
    if (fa_len($name) < 3 || preg_match('/\d/', $name)) {
        return null;
    }
    return $name;
}

/* ───────────── Fast Path Router ───────────── */

/**
 * تصمیم می‌گیرد این جمله را می‌شود بدون AI جواب داد یا نه.
 * خروجی: ['action' => ..., 'needs_ai' => bool]
 *
 * actionها: end | book | next_slot | got_phone | got_name | ai
 */
function fa_route(string $text, string $stage): array
{
    if (fa_is_farewell_only($text) && $stage !== 'awaiting_info') {
        return ['action' => 'end', 'needs_ai' => false];
    }

    if ($stage === 'awaiting_confirm') {
        if (fa_is_confirm($text) && !fa_is_reject($text)) {
            return ['action' => 'book', 'needs_ai' => false];
        }
        if (fa_is_reject($text)) {
            return ['action' => 'next_slot', 'needs_ai' => false];
        }
    }

    if ($stage === 'awaiting_info') {
        if (fa_phone($text) !== null || fa_name($text) !== null) {
            return ['action' => 'got_info', 'needs_ai' => false];
        }
    }

    return ['action' => 'ai', 'needs_ai' => true];
}
